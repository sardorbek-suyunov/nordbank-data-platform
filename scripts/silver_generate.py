_quote = dbt_generate._quote


def render_sql(silver: Silver) -> str:
    spec = silver.spec
    key = ", ".join(f"'{k}'" for k in silver.key)
    call = f"{spec.history}(ref('{silver.bronze.name}'), [{key}]"
    if spec.excluded:
        call += ", excluded=[" + ", ".join(f"'{e}'" for e in spec.excluded) + "]"
    if spec.deleted != "is_deleted":
        call += f", deleted='{spec.deleted}'"
    call += ")"
    header = (
        f"-- Generated by scripts/silver_generate.py from {silver.bronze.contract_path}; "
        "do not edit.\n"
    )
    if not any(a.name == "_business_valid_from_date" for a in spec.added):
        return header + f"{{{{ {call} }}}}\n"
    return (
        header
        + "select\n"
        + "    *,\n"
        + "    valid_from_date as _business_valid_from_date,\n"
        + "    {{ business_valid_to('valid_to_date') }} as _business_valid_to_date\n"
        + f"from (\n    {{{{ {call} }}}}\n)\n"
    )


def _describe_model(silver: Silver) -> str:
    spec = silver.spec
    grain = ", ".join(f"`{c}`" for c in silver.grain)
    if spec.history == SCD2:
        kind = (
            "One row per version (SCD2): a version opens when a projection column changes, or "
            "when no contract column changed at all"
        )
        if spec.excluded:
            kind += "; a change confined to " + ", ".join(f"`{e}`" for e in spec.excluded)
            kind += " opens none, and it is not carried"
        kind += "."
    else:
        kind = "One row per entity, its latest observation; a soft-deleted entity is absent."
    if spec.deleted == "false":
        deleted = " An inactive row is retained as a version, current with `is_active` false."
    elif spec.history == SCD2:
        deleted = " A soft delete closes the final version and leaves no current one."
    else:
        deleted = ""
    return (
        f"Silver {spec.entity}, from `{silver.bronze.name}` ({silver.bronze.contract_path}). "
        f"{kind}{deleted} Re-reads of one version collapse to the earliest batch. "
        f"Grain: {grain}."
    )


def render_yml(silver: Silver) -> str:
    spec = silver.spec
    grain = ", ".join(silver.grain)
    key = ", ".join(silver.key)
    lines = [
        "# Generated by scripts/silver_generate.py from the contracts; do not edit.",
        "version: 2",
        "models:",
        f"  - name: {silver.name}",
        "    description: " + _quote(_describe_model(silver)),
        "    config:",
        "      meta:",
        f"        entity: {spec.entity}",
        f"        history: {spec.history}",
        f"        upstream: {silver.bronze.name}",
        f"        grain: [{grain}]",
        f"        excluded: [{', '.join(spec.excluded)}]",
        f"        generated_sql: {'true' if spec.generated else 'false'}",
        "    data_tests:",
        "      - silver_unique_key:",
        "          arguments:",
        f"            columns: [{grain}]",
        "          config:",
        "            severity: error",
        "      - silver_not_null:",
        "          arguments:",
        f"            columns: [{grain}]",
        "          config:",
        "            severity: error",
        "      - silver_min_rows:",
        "          arguments:",
        f"            minimum: {spec.floor}",
        "          config:",
        "            severity: error",
        "      - silver_rereads_agree:",
        "          arguments:",
        f"            upstream: ref('{silver.bronze.name}')",
        f"            key: [{key}]",
        "          config:",
        "            severity: error",
    ]
    if spec.history == SCD2:
        lines += [
            "      - silver_scd2_intervals:",
            "          arguments:",
            f"            key: [{key}]",
            f"            upstream: ref('{silver.bronze.name}')",
        ]
        if spec.deleted != "is_deleted":
            lines.append(f'            deleted: "{spec.deleted}"')
        lines += [
            "          config:",
            "            severity: error",
        ]
    # With no excluded measure every observation that is not a soft delete opens a version, the
    # merchants case included; with one, a singular test checks the rule against bronze.
    if spec.history == SCD2 and not spec.excluded:
        lines += [
            "      - silver_observations_versioned:",
            "          arguments:",
            f"            upstream: ref('{silver.bronze.name}')",
            f"            key: [{key}]",
        ]
        if spec.deleted != "is_deleted":
            lines.append(f'            deleted: "{spec.deleted}"')
        lines += [
            "          config:",
            "            severity: error",
        ]
    if spec.converts:
        amount, currency = spec.converts
        lines += [
            "      - silver_fx_provenance:",
            "          arguments:",
            f"            key: {silver.key[0]}",
            f"            amount: {amount}",
            f"            currency: {currency}",
            "          config:",
            "            severity: error",
        ]
    lines.append("    columns:")
    resolves = {column: (to, to_column) for column, to, to_column in spec.resolves}
    splits = {column: (yes, no) for column, yes, no in spec.splits}
    permitted = gold_permitted()
    for column in silver.columns:
        lines += [
            f"      - name: {column.name}",
            f"        data_type: {column.data_type}",
            "        description: " + _quote(column.description),
            "        config:",
            "          meta:",
            f"            classification: {column.classification}",
        ]
        if (silver.name, column.name) in permitted:
            lines.append(
                "            gold_generalisation: " + _quote(permitted[(silver.name, column.name)])
            )
        tests = []
        if column.name in resolves:
            to, to_column = resolves.pop(column.name)
            tests += [
                "          - silver_resolves_one_version:",
                "              arguments:",
                f"                to: ref('{to}')",
                f"                to_column: {to_column}",
                "                at: " + _quote(spec.instant),
                "              config:",
                "                severity: error",
            ]
        if column.name in splits:
            yes, no = splits.pop(column.name)
            tests += [
                "          - silver_flag_split:",
                "              arguments:",
                f"                minimum_true: {yes}",
                f"                minimum_false: {no}",
                "              config:",
                "                severity: error",
            ]
        if tests:
            lines += ["        data_tests:", *tests]
    if resolves or splits:
        unknown = sorted([*resolves, *splits])
        raise SystemExit(f"silver-generate: {silver.name} tests unknown columns {unknown}")
    return "\n".join(lines) + "\n"


def _consumers(text: str) -> dict[str, set[str]]:
    """Who reads each silver model: the planned models whose upstream names it, outside the
    generated section, and for a `ref` table the consumer the data dictionary's listing names."""
    head = text.split(BEGIN, 1)[0] + text.split(END, 1)[-1]
    out: dict[str, set[str]] = defaultdict(set)
    for line in head.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 3 or not cells[0].startswith("`"):
            continue
        for name in re.findall(r"`(sl_[a-z_]+)`", cells[2]):
            out[name].add(cells[0])
    listing = DICTIONARY.read_text(encoding="utf-8").split(dbt_generate.REFERENCE_LISTING, 1)[-1]
    for line in listing.split("\n## ", 1)[0].splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) == 3 and cells[0].startswith("`") and cells[2] != "Consumed by":
            out[f"sl_{cells[0].strip('`')}"].add(cells[2])
    return out


def render_inventory(models: list[Silver], text: str) -> str:
    if BEGIN not in text or END not in text:
        raise SystemExit("silver-generate: docs/model_inventory.md has no silver markers")
    consumers = _consumers(text)
    generated = [m for m in models if m.spec.generated]
    rows = [
        "| Object | Grain | Upstream | Consumed by |",
        "|---|---|---|---|",
    ]
    for model in generated:
        if not consumers.get(model.name):
            raise SystemExit(
                f"silver-generate: {model.name} has no consumer in docs/model_inventory.md or "
                "the data dictionary's reference listing"
            )
        grain = "One row per version (SCD2): " + ", ".join(f"`{c}`" for c in model.grain)
        rows.append(
            f"| `{model.name}` | {grain} | `{model.bronze.name}` | "
            f"{'; '.join(sorted(consumers[model.name]))} |"
        )
    block = "\n".join(
        [
            BEGIN,
            "",
            f"{len(generated)} models generated from the contracts by `make silver-generate`: "
            "every `ref` table and `agent_locations`, each the entity historised and nothing "
            "more. An inactive `ref` row is retained as a version, current with `is_active` "
            "false.",
            "",
            *rows,
            "",
            END,
        ]
    )
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    return head + block + tail


def outputs() -> dict[Path, str]:
    models = build()
    files: dict[Path, str] = {}
    for model in models:
        files[MODELS / f"{model.name}.yml"] = render_yml(model)
        if model.spec.generated:
            files[MODELS / f"{model.name}.sql"] = render_sql(model)
    for feed in build_feeds():
        files[MODELS / f"{feed.feed.name}.yml"] = render_feed_yml(feed)
    files[INVENTORY] = render_inventory(models, INVENTORY.read_text(encoding="utf-8"))
    return files


def _generated_on_disk() -> set[Path]:
    """The silver files this generator wrote, recognised by their first line."""
    found = set()
    for path in MODELS.glob("sl_*.*"):
        first = path.read_text(encoding="utf-8").split("\n", 1)[0]
        if "Generated by scripts/silver_generate.py" in first:
            found.add(path)
    return found


def _shown(path: Path) -> str:
    try:
        return path.relative_to(ROOT).as_posix()
    except ValueError:
        return path.as_posix()


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    arguments = parser.parse_args(argv)

    wanted = outputs()
    stale = sorted(_generated_on_disk() - set(wanted))
    if arguments.check:
        differing = [
            path
            for path, text in wanted.items()
            if not path.exists() or path.read_text(encoding="utf-8") != text
        ]
        for path in differing + stale:
            print(f"silver-generate: {_shown(path)} differs from the contracts")
        if differing or stale:
            print("silver-generate: run `make silver-generate` and commit the result")
            return 1
        models = sum(1 for p in wanted if p.suffix == ".yml")
        sql = sum(1 for p in wanted if p.suffix == ".sql")
        print(
            f"silver-generate: {models} silver models' properties, {sql} generated models and "
            "the inventory agree with the contracts"
        )
        return 0

    MODELS.mkdir(parents=True, exist_ok=True)
    for path in stale:
        path.unlink()
    for path, text in wanted.items():
        path.write_text(text, encoding="utf-8", newline="\n")
    print(f"silver-generate: wrote {len(wanted)} file(s), removed {len(stale)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
