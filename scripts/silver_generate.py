"""Generate the silver models that mirror a contract entity (specification 008 sections 2 and 5).

The contracts are the one source for what an entity carries, and `scripts/dbt_generate.py`
already reads them into the bronze models' columns, types, descriptions and classifications.
This builds on its `build_models()` and writes, for every silver model that mirrors one
relational entity:

- the model's properties, `dbt/models/silver/sl_<entity>.yml`: every column silver carries, with
  the bronze column's type, description and classification, the columns silver adds, its grain,
  its tests and its minimum cardinality; every silver model's contract is enforced
  (`dbt_project.yml`), so a model whose SQL returns anything else fails to build;
- for every `ref` table and for `agent_locations`, the model itself, `sl_<entity>.sql`, which is
  one call to the historisation macro: their silver is the contract's columns historised and
  nothing more, so writing them by hand would be thirty copies of one line;
- the generated section of the inventory's silver listing, between its markers.

A model with logic of its own, such as `sl_transactions`, which converts its amount, is written
by hand: this generates its properties and leaves its SQL alone, and the enforced contract holds
the two together.

`--check` regenerates everything in memory and fails on any difference, so a hand edit to a
generated file, or a contract changed without regenerating, fails in CI: the `dbt-generate`
pattern. Run it before `make dbt-generate`, whose bronze consumer lists read this section.

**What a mirroring model carries.** Its key, every contract column of its projection, the
version's `created_at` and `updated_at`, the `_batch_id` that read it, and for SCD2 the validity
columns. It does not carry `is_deleted`, which is false on every row silver keeps, the excluded
measures, which open no version and are wrong on every row but the one that opened it, or the
other audit columns, which describe a read rather than the entity.

**The external feeds** (specification 009) are not entities with versions: a clearing file's
records, a list snapshot's entities and a series' observations. Their silver is written by hand,
and `FEEDS` states, for each, the bronze columns it carries, under the same or a new name and
type, the columns it adds, its grain and its floor; their properties are generated from that and
the feed contracts the same way, so a column's type, description and classification still have
one source.
"""

